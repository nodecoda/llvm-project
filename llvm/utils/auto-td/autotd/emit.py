"""TableGen emission.

The output is deliberately *flat*: one ``def`` per instruction, every bit
assigned explicitly, no multiclass and no inheritance beyond the target's own
base class.  That is what makes the records diffable and what removes the
"pick the right reuse point" failure mode.
"""

from __future__ import annotations

from .encoding import assignments, field_declarations, instruction_format
from .model import InstrSpec


def _cfg(config: dict, key: str, default):
    return config.get(key, default)


def operand_class(spec: InstrSpec, config: dict, name: str) -> str:
    return str((config.get("operand_classes") or {}).get(name, name))


def _dag(spec: InstrSpec, config: dict, direction: str) -> str:
    operands = spec.outs if direction == "outs" else spec.ins
    if not operands:
        return f"({direction})"
    rendered = ", ".join(
        f"{operand_class(spec, config, op.td_class)}:${op.field}" for op in operands
    )
    return f"({direction} {rendered})"


def asm_string(spec: InstrSpec) -> str:
    parts = [f"${op.field}" for op in spec.outs]
    values = [op for op in spec.ins if not op.is_mask]
    base = next((op for op in values if op.role == "base"), None)
    offset = next((op for op in values if op.role == "offset"), None)
    folded = base is not None and offset is not None

    for op in values:
        if folded and op in (base, offset):
            continue
        parts.append(f"${op.field}")
    if folded:
        parts.append(f"${{{offset.field}}}(${{{base.field}}})")

    text = ", ".join(parts)
    mask = spec.mask_operand
    if mask is not None:
        text += f", ${mask.field}" if mask.is_carry_mask else f"${mask.field}"
    return text


def _flags(spec: InstrSpec, config: dict) -> list[str]:
    lines = [
        f"  let Predicates = [{spec.predicate}];",
        f"  let hasSideEffects = {int(spec.effects.side_effects)};",
        f"  let mayLoad = {int(spec.effects.may_load)};",
        f"  let mayStore = {int(spec.effects.may_store)};",
    ]
    for flag in spec.effects.flags:
        if flag in {"hasSideEffects", "mayLoad", "mayStore"}:
            continue
        lines.append(f"  let {flag} = 1;")
    if spec.sched is not None:
        lines.append(f"  let SchedRW = [{', '.join(spec.sched)}];")
    elif _cfg(config, "emit_scheduling_stub", True) and "hasNoSchedulingInfo" not in spec.effects.flags:
        lines.append("  let hasNoSchedulingInfo = 1;")
    if spec.effects.implicit_uses:
        lines.append(f"  let Uses = [{', '.join(spec.effects.implicit_uses)}];")
    if spec.effects.implicit_defs:
        lines.append(f"  let Defs = [{', '.join(spec.effects.implicit_defs)}];")
    return lines


def render_record(spec: InstrSpec, config: dict, prefix: str) -> list[str]:
    items = assignments(spec)
    base_class = str(_cfg(config, "base_class", "RVInst"))
    fmt = instruction_format(spec, config.get("formats") or {})

    head = (
        f"def {spec.record_name(prefix)} : {base_class}<{_dag(spec, config, 'outs')}, "
        f"{_dag(spec, config, 'ins')}, \"{spec.mnemonic}\", \"{asm_string(spec)}\", [], {fmt}> {{"
    )
    lines = [
        f"// auto-td: {spec.mnemonic}",
        f"//   opcode: {spec.ref}",
        f"//   spec:   {spec.spec_ref}",
        head,
    ]
    lines += _flags(spec, config)
    lines += [f"  {decl}" for decl in field_declarations(spec)]
    lines += [f"  let {item.range_text()} = {item.expr};" for item in items]
    lines.append("}")
    return lines


def render_instrinfo(specs: list[InstrSpec], config: dict) -> str:
    prefix = str(_cfg(config, "record_prefix", "AUTO"))
    note = f" (prefix {prefix})" if prefix else ""
    lines = [f"// generated by auto-td-gen{note}; do not edit", ""]
    for spec in sorted(specs, key=lambda s: s.mnemonic):
        lines += render_record(spec, config, prefix)
        lines.append("")

    aliases = [(alias, spec.mnemonic) for spec in specs for alias in spec.aliases]
    for alias, canonical in sorted(aliases):
        lines.append(f'def : MnemonicAlias<"{alias}", "{canonical}">;')
    return "\n".join(lines).rstrip() + "\n"


def render_manifests(specs: list[InstrSpec]) -> str:
    """Audit manifest: what the YAML *claims*, for humans and for guards."""
    lines = ["// generated by auto-td-gen; audit manifest, not instruction data"]
    for spec in sorted(specs, key=lambda s: s.mnemonic):
        if spec.pseudos:
            matrix = spec.pseudos.get("matrix") or {}
            detail = " ".join(f"{k}={matrix[k]}" for k in sorted(matrix))
            lines.append(f"// pseudo {spec.mnemonic}: {detail}".rstrip())
        for pattern in spec.patterns:
            lines.append(f"// pattern {spec.mnemonic}: {_flat(pattern)}")
        if spec.builtin:
            names = ",".join(spec.builtin.get("names") or [])
            codegen = str(bool(spec.builtin.get("codegen"))).lower()
            lines.append(f"// builtin {spec.mnemonic}: header={spec.builtin.get('header')} names={names} codegen={codegen}")
    return "\n".join(lines) + "\n"


def _flat(mapping: dict) -> str:
    return " ".join(f"{k}={mapping[k]}" for k in sorted(mapping))


def _codegen_builtins(specs: list[InstrSpec]):
    for spec in sorted(specs, key=lambda s: s.mnemonic):
        if not spec.builtin or not spec.builtin.get("codegen"):
            continue
        pattern = next((p for p in spec.patterns if p.get("kind") == "intrinsic_to_pseudo"), None)
        if pattern is None:
            continue
        for name in spec.builtin.get("names") or []:
            yield spec, pattern, str(name)


def _builtin_type(name: str, config: dict) -> str:
    types = (config.get("builtins") or {}).get("types") or {}
    for suffix, ctype in types.items():
        if name.endswith("_" + suffix):
            return str(ctype)
    raise ValueError(f"builtin {name!r}: no C type registered in config builtins.types")


def _builtin_arity(spec: InstrSpec) -> int:
    return len(spec.outs) + len([op for op in spec.ins if not op.is_mask])


def render_clang_builtins_td(specs: list[InstrSpec], config: dict) -> str:
    builtins_cfg = config.get("builtins") or {}
    klass = str(builtins_cfg.get("class", "TargetBuiltin"))
    features = str(builtins_cfg.get("features", ""))
    lines = ["// generated by auto-td-gen", "let Attributes = [NoThrow, Const] in {"]
    for spec, _pattern, name in _codegen_builtins(specs):
        ctype = _builtin_type(name, config)
        params = ", ".join([ctype] * _builtin_arity(spec) + ["unsigned long int"])
        lines.append(f'def {name.removeprefix("ysx_")} : {klass}<"{ctype}({params})", "{features}">;')
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_clang_builtin_cg_inc(specs: list[InstrSpec], config: dict) -> str:
    lines = ["// generated by auto-td-gen"]
    for spec, pattern, name in _codegen_builtins(specs):
        intrinsic = str(pattern["intrinsic"]).replace(".", "_")
        types = ", ".join(["ResultType"] + [f"Ops[{i}]->getType()" for i in range(_builtin_arity(spec))])
        lines += [
            f"case {name}: {{",
            f"  llvm::Function *Fn = CGM.getIntrinsic(Intrinsic::{intrinsic}, {{{types}}});",
            '  return Builder.CreateCall(Fn, Ops, "");',
            "}",
        ]
    return "\n".join(lines) + "\n"


def render_llvm_intrinsics_td(specs: list[InstrSpec], config: dict) -> str:
    lines = ["// generated by auto-td-gen"]
    seen: set[str] = set()
    for spec, pattern, _name in _codegen_builtins(specs):
        intrinsic = str(pattern["intrinsic"])
        if intrinsic in seen:
            continue
        seen.add(intrinsic)
        params = ", ".join(["LLVMMatchType<0>"] * _builtin_arity(spec) + ["llvm_anyint_ty"])
        lines += [
            f"def int_{intrinsic.replace('.', '_')}",
            "    : DefaultAttrsIntrinsic<[llvm_anyvector_ty],",
            f"                            [{params}],",
            "                            [IntrNoMem, IntrSpeculatable]>;",
        ]
    return "\n".join(lines) + "\n"
