"""Chapter 21 sample: the i32 vector add used as the frontend contract.

The C++ tool only parses this file in chapter 21; chapters 22-24 lower it to
TTIR and then to GPUMin LLVM IR.
"""

import triton
import triton.language as tl


@triton.jit
def add_kernel(x_ptr, y_ptr, out_ptr, n, BLOCK: tl.constexpr):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n
    x = tl.load(x_ptr + offs, mask=mask)
    y = tl.load(y_ptr + offs, mask=mask)
    tl.store(out_ptr + offs, x + y, mask=mask)
