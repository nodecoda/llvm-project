// Chapter 00 has no patterns, so this selector rejects every DAG node.  It
// exists to prove the target is wired into SelectionDAG: chapter 03 adds the
// first pattern (ret) and chapter 04 the ALU patterns.
//
// The manual Select hook is where later chapters add nodes that patterns
// cannot express: large constants, branches, frame indices and globals.
//
//===----------------------------------------------------------------------===//

#include "GPUMinISelDAGToDAG.h"
#include "GPUMinSubtarget.h"
#include "GPUMinTargetMachine.h"
#include "llvm/CodeGen/SelectionDAGISel.h"
#include "llvm/CodeGen/SelectionDAGNodes.h"
#include "llvm/Support/Debug.h"

using namespace llvm;

#define DEBUG_TYPE "gpumin-isel"

namespace {

class GPUMinDAGToDAGISel : public SelectionDAGISel {
  const GPUMinSubtarget *Subtarget = nullptr;

public:
  GPUMinDAGToDAGISel(TargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISel(TM, OptLevel) {}

  void Select(SDNode *N) override;

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<GPUMinSubtarget>();
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

// Include the pieces autogenerated from the target description.
#include "GPUMinGenDAGISel.inc"
};

} // end anonymous namespace

void GPUMinDAGToDAGISel::Select(SDNode *N) {
  SelectCode(N);
}

GPUMinDAGToDAGISelPass::GPUMinDAGToDAGISelPass(TargetMachine &TM)
    : SelectionDAGISelPass(
          std::make_unique<GPUMinDAGToDAGISel>(TM, TM.getOptLevel())) {}
