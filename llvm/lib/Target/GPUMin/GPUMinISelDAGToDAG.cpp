namespace {

// Address spaces, matching scripts/simt-model.json.
enum GPUMinAddressSpace : unsigned {
  AS_GLOBAL = 1,
  AS_SHARED = 2,
  AS_LOCAL = 3,
  AS_CONST = 4,
};

// Chapter 16: the memory opcode names its address space in bits [4:3], but
// tablegen patterns cannot look at a load's address space, so AS1 (global)
// keeps the patterns and the other three spaces are selected by hand here.
unsigned pickLoadOpcode(unsigned AS, EVT MemVT, ISD::LoadExtType Ext) {
  bool Signed = Ext == ISD::SEXTLOAD;
  switch (MemVT.getSimpleVT().SimpleTy) {
  case MVT::i8:
    if (AS == AS_SHARED)
      return Signed ? GPUMin::LD_SHARED_S8 : GPUMin::LD_SHARED_U8;
    if (AS == AS_LOCAL)
      return Signed ? GPUMin::LD_LOCAL_S8 : GPUMin::LD_LOCAL_U8;
    return Signed ? GPUMin::LD_CONST_S8 : GPUMin::LD_CONST_U8;
  case MVT::i16:
    if (AS == AS_SHARED)
      return Signed ? GPUMin::LD_SHARED_S16 : GPUMin::LD_SHARED_U16;
    if (AS == AS_LOCAL)
      return Signed ? GPUMin::LD_LOCAL_S16 : GPUMin::LD_LOCAL_U16;
    return Signed ? GPUMin::LD_CONST_S16 : GPUMin::LD_CONST_U16;
  case MVT::i32:
    if (AS == AS_SHARED)
      return GPUMin::LD_SHARED_B32;
    if (AS == AS_LOCAL)
      return GPUMin::LD_LOCAL_B32;
    return GPUMin::LD_CONST_B32;
  default:
    llvm_unreachable("GPUMin: unexpected load width");
  }
}

unsigned pickStoreOpcode(unsigned AS, EVT MemVT) {
  bool Shared = AS == AS_SHARED;
  switch (MemVT.getSimpleVT().SimpleTy) {
  case MVT::i8:
    return Shared ? GPUMin::ST_SHARED_B8 : GPUMin::ST_LOCAL_B8;
  case MVT::i16:
    return Shared ? GPUMin::ST_SHARED_B16 : GPUMin::ST_LOCAL_B16;
  case MVT::i32:
    return Shared ? GPUMin::ST_SHARED_B32 : GPUMin::ST_LOCAL_B32;
  default:
    llvm_unreachable("GPUMin: unexpected store width");
  }
}

class GPUMinDAGToDAGISel : public SelectionDAGISel {
  const GPUMinSubtarget *Subtarget = nullptr;

  /// Static offset of every address-space-2 global inside the block's shared
  /// window.  Chapter 16 assigns them in declaration order, so the layout is
  /// deterministic for a given module without a separate allocation pass.
  DenseMap<const GlobalValue *, int64_t> SharedOffsets;

  void assignSharedOffsets(const Module &M) {
    SharedOffsets.clear();
    const DataLayout &DL = M.getDataLayout();
    int64_t Next = 0;
    for (const GlobalVariable &GV : M.globals()) {
      if (GV.getAddressSpace() != AS_SHARED || GV.isDeclaration())
        continue;
      Next = alignTo(Next, GV.getAlign().valueOrOne());
      SharedOffsets[&GV] = Next;
      Next += DL.getTypeAllocSize(GV.getValueType());
    }
  }

public:
  GPUMinDAGToDAGISel(TargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISel(TM, OptLevel) {}

  void Select(SDNode *N) override;

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<GPUMinSubtarget>();
    assignSharedOffsets(*MF.getFunction().getParent());
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

// Include the pieces autogenerated from the target description.
#include "GPUMinGenDAGISel.inc"
};

} // end anonymous namespace

void GPUMinDAGToDAGISel::Select(SDNode *N) {
  // Chapter 16: a shared global has no symbol in the object file.  Its address
  // is the block's window base plus a static offset, so it lowers to
  // `sr.shared` and an add -- the counterpart of a stack slot, but in address
  // space 2 and shared by every warp of the block.
  if (N->getOpcode() == ISD::GlobalAddress) {
    auto *GA = cast<GlobalAddressSDNode>(N);
    if (GA->getAddressSpace() == AS_SHARED) {
      auto It = SharedOffsets.find(GA->getGlobal());
      if (It == SharedOffsets.end())
        report_fatal_error("GPUMin: shared global has no window offset");
      SDLoc DL(N);
      int64_t Off = It->second + GA->getOffset();
      if (!isInt<16>(Off))
        report_fatal_error("GPUMin: shared offset does not fit 16 bits");
      SDValue Base = SDValue(
          CurDAG->getMachineNode(GPUMin::SR_SHARED, DL, MVT::i32), 0);
      SDNode *Addr = Base.getNode();
      if (Off != 0)
        Addr = CurDAG->getMachineNode(
            GPUMin::ADDI, DL, MVT::i32, Base,
            CurDAG->getTargetConstant(Off, DL, MVT::i32));
      ReplaceNode(N, Addr);
      return;
    }
  }

  // Chapter 16: address-space-aware memory selection.  Global (AS1) stays with
  // the tablegen patterns; shared, local and constant are picked here so the
  // opcode's space field matches the IR pointer's address space.
  if (N->getOpcode() == ISD::LOAD) {
    auto *LD = cast<LoadSDNode>(N);
    unsigned AS = LD->getAddressSpace();
    if (AS != AS_GLOBAL) {
      SDLoc DL(N);
      // The displacement stays zero: a static offset is already folded into
      // the address by the GlobalAddress lowering above, and a dynamic index
      // is a plain register add.  The 11-bit field is still exercised by the
      // global patterns, which match `simm11imm` directly.
      unsigned Opc =
          pickLoadOpcode(AS, LD->getMemoryVT(), LD->getExtensionType());
      // The chain goes last: InstrEmitter ignores a trailing MVT::Other
      // operand when it maps DAG operands onto the instruction.
      SDValue Ops[] = {LD->getBasePtr(),
                       CurDAG->getTargetConstant(0, DL, MVT::i32),
                       LD->getChain()};
      SDNode *Inst = CurDAG->getMachineNode(
          Opc, DL, CurDAG->getVTList(MVT::i32, MVT::Other), Ops);
      CurDAG->setNodeMemRefs(cast<MachineSDNode>(Inst), {LD->getMemOperand()});
      ReplaceNode(N, Inst);
      return;
    }
  }

  if (N->getOpcode() == ISD::STORE) {
    auto *ST = cast<StoreSDNode>(N);
    unsigned AS = ST->getAddressSpace();
    if (AS != AS_GLOBAL) {
      if (AS == AS_CONST)
        report_fatal_error("GPUMin: the constant space is read-only");
      SDLoc DL(N);
      unsigned Opc = pickStoreOpcode(AS, ST->getMemoryVT());
      SDValue Ops[] = {ST->getValue(), ST->getBasePtr(),
                       CurDAG->getTargetConstant(0, DL, MVT::i32),
                       ST->getChain()};
      SDNode *Inst = CurDAG->getMachineNode(Opc, DL, MVT::Other, Ops);
      CurDAG->setNodeMemRefs(cast<MachineSDNode>(Inst), {ST->getMemOperand()});
      ReplaceNode(N, Inst);
      return;
    }
  }

  // Constants are the one node chapter 03 cannot express as a pattern:
  // `movi` only carries 16 bits, and a pattern would happily match a 32-bit
  // constant and truncate it.  Doing the range check here keeps the failure
  // explicit.  Chapter 04 adds the two-instruction sequence for wide values.
  if (N->getOpcode() == ISD::Constant) {
    auto *C = cast<ConstantSDNode>(N);
    int64_t V = C->getSExtValue();
    SDLoc DL(N);
    if (isInt<16>(V)) {
      SDValue Imm =
          CurDAG->getTargetConstant(static_cast<uint32_t>(V), DL, MVT::i32);
      SDNode *Mov = CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32, Imm);
      ReplaceNode(N, Mov);
      return;
    }
    // Chapter 08: a 16-bit *unsigned* constant (the 0xff/0xffff masks the
    // type legalizer inserts for i8/i16 arithmetic) is still reachable.
    // movi sign-extends, so materialise V and clear the high half:
    //   movi rd, V; movi rt, 16; shl rd, rd, rt; shr rd, rd, rt
    if (isUInt<16>(C->getZExtValue())) {
      // Print/encode the canonical signed 16-bit form (-1 for 0xffff): the
      // field is simm16 and the assembler rejects 65535.  The low 16 bits are
      // identical, and the shift pair clears the sign extension afterwards.
      int32_t SImm = static_cast<int16_t>(V);
      SDValue Imm =
          CurDAG->getTargetConstant(static_cast<uint32_t>(SImm), DL, MVT::i32);
      SDNode *Mov = CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32, Imm);
      SDValue Sixteen = SDValue(
          CurDAG->getMachineNode(
              GPUMin::MOVI, DL, MVT::i32,
              CurDAG->getTargetConstant(16, DL, MVT::i32)),
          0);
      SDValue Shl = SDValue(
          CurDAG->getMachineNode(GPUMin::SHL, DL, MVT::i32, SDValue(Mov, 0),
                                 Sixteen),
          0);
      SDNode *Shr = CurDAG->getMachineNode(GPUMin::SHR, DL, MVT::i32, Shl,
                                           Sixteen);
      ReplaceNode(N, Shr);
      return;
    }
    // A general 32-bit constant.  `movi` sign-extends, so the low half is
    // materialised and then shifted up and logically back down to clear the
    // ones above bit 15; the high half only needs one shift.
    //   movi rd, hi; movi rt, 16; shl rd, rd, rt
    //   movi rt2, lo; shl rt2, rt2, rt; shr rt2, rt2, rt
    //   or rd, rd, rt2
    int32_t Hi = static_cast<int16_t>((V >> 16) & 0xffff);
    int32_t Lo = static_cast<int16_t>(V & 0xffff);
    SDValue Sixteen = SDValue(
        CurDAG->getMachineNode(
            GPUMin::MOVI, DL, MVT::i32,
            CurDAG->getTargetConstant(16, DL, MVT::i32)),
        0);
    SDValue HiMov = SDValue(
        CurDAG->getMachineNode(
            GPUMin::MOVI, DL, MVT::i32,
            CurDAG->getTargetConstant(static_cast<uint32_t>(Hi), DL,
                                      MVT::i32)),
        0);
    SDValue HiShifted = SDValue(
        CurDAG->getMachineNode(GPUMin::SHL, DL, MVT::i32, HiMov, Sixteen), 0);
    SDValue LoMov = SDValue(
        CurDAG->getMachineNode(
            GPUMin::MOVI, DL, MVT::i32,
            CurDAG->getTargetConstant(static_cast<uint32_t>(Lo), DL,
                                      MVT::i32)),
        0);
    SDValue LoShifted = SDValue(
        CurDAG->getMachineNode(GPUMin::SHL, DL, MVT::i32, LoMov, Sixteen), 0);
    SDValue LoClean = SDValue(
        CurDAG->getMachineNode(GPUMin::SHR, DL, MVT::i32, LoShifted, Sixteen),
        0);
    SDNode *Combined = CurDAG->getMachineNode(GPUMin::OR, DL, MVT::i32,
                                              HiShifted, LoClean);
    ReplaceNode(N, Combined);
    return;
  }

  // Sign-extending a promoted i8/i16: the high bits of the i32 register are
  // undefined, so the extension is a shift pair (shl by 32-bits, sar back).
  if (N->getOpcode() == ISD::SIGN_EXTEND_INREG) {
    EVT InnerVT = cast<VTSDNode>(N->getOperand(1))->getVT();
    unsigned Bits = InnerVT.getSizeInBits();
    if (Bits == 8 || Bits == 16) {
      SDLoc DL(N);
      SDValue ShiftAmt = SDValue(
          CurDAG->getMachineNode(
              GPUMin::MOVI, DL, MVT::i32,
              CurDAG->getTargetConstant(32 - Bits, DL, MVT::i32)),
          0);
      SDValue Shl = SDValue(
          CurDAG->getMachineNode(GPUMin::SHL, DL, MVT::i32, N->getOperand(0),
                                 ShiftAmt),
          0);
      SDNode *Sar =
          CurDAG->getMachineNode(GPUMin::SAR, DL, MVT::i32, Shl, ShiftAmt);
      ReplaceNode(N, Sar);
      return;
    }
  }

  // Boolean algebra on predicates.  GM32 has no predicate ALU and no
  // predicate NOT, so the only way to combine two 1-bit values is to widen
  // them to 0/1 in GPRs, use the integer ALU, and narrow back with SETP.
  // `xor %p, true` is the NOT case: the combiner produces it whenever an i1
  // comparison is negated, so it is worth the one-instruction shortcut.
  if (N->getValueType(0) == MVT::i1 && N->getOpcode() == ISD::XOR &&
      isAllOnesConstant(N->getOperand(1))) {
    SDLoc DL(N);
    SDValue Zero = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(0, DL, MVT::i32)),
        0);
    SDValue One = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(1, DL, MVT::i32)),
        0);
    SDValue Bool = SDValue(
        CurDAG->getMachineNode(GPUMin::SELP, DL, MVT::i32, N->getOperand(0),
                               One, Zero),
        0);
    SDNode *Setp = CurDAG->getMachineNode(GPUMin::SETP_EQ, DL, MVT::i1, Bool,
                                          Zero);
    ReplaceNode(N, Setp);
    return;
  }

  if (N->getValueType(0) == MVT::i1 &&
      (N->getOpcode() == ISD::AND || N->getOpcode() == ISD::OR ||
       N->getOpcode() == ISD::XOR)) {
    SDLoc DL(N);
    SDValue Zero = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(0, DL, MVT::i32)),
        0);
    SDValue One = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(1, DL, MVT::i32)),
        0);
    auto ToInt = [&](SDValue Pred) {
      return SDValue(CurDAG->getMachineNode(GPUMin::SELP, DL, MVT::i32, Pred,
                                            One, Zero),
                     0);
    };
    unsigned Opc = N->getOpcode() == ISD::AND   ? GPUMin::AND
                   : N->getOpcode() == ISD::OR  ? GPUMin::OR
                                                : GPUMin::XOR;
    SDValue Bits = SDValue(
        CurDAG->getMachineNode(Opc, DL, MVT::i32, ToInt(N->getOperand(0)),
                               ToInt(N->getOperand(1))),
        0);
    SDNode *Setp =
        CurDAG->getMachineNode(GPUMin::SETP_NE, DL, MVT::i1, Bits, Zero);
    ReplaceNode(N, Setp);
    return;
  }

  // i32 -> i1 truncation.  A predicate register stores one bit, and GM32 has
  // neither a bitfield extract nor an immediate AND, so "take bit 0" costs a
  // mask plus a compare: movi 1; and; movi 0; setp.ne.  The two constants are
  // identical in every function and get coalesced by machine CSE.
  //
  // This shows up more than it looks: `icmp ne (x & 1), 0` is precisely how
  // C code spells a boolean test, and the DAG combiner canonicalises it to a
  // truncate before isel sees it.
  if (N->getOpcode() == ISD::TRUNCATE && N->getValueType(0) == MVT::i1 &&
      N->getOperand(0).getValueType() == MVT::i32) {
    SDLoc DL(N);
    SDValue One = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(1, DL, MVT::i32)),
        0);
    SDValue Zero = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(0, DL, MVT::i32)),
        0);
    SDValue Low = SDValue(
        CurDAG->getMachineNode(GPUMin::AND, DL, MVT::i32, N->getOperand(0),
                               One),
        0);
    SDNode *Setp =
        CurDAG->getMachineNode(GPUMin::SETP_NE, DL, MVT::i1, Low, Zero);
    ReplaceNode(N, Setp);
    return;
  }

  // i1 -> i32.  A predicate register holds one bit, not a 0/1 value, so the
  // extension is a SELP against constants: 0/1 for zext, 0/-1 for sext.
  if ((N->getOpcode() == ISD::ZERO_EXTEND ||
       N->getOpcode() == ISD::ANY_EXTEND) &&
      N->getOperand(0).getValueType() == MVT::i1) {
    SDLoc DL(N);
    SDValue One = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(1, DL, MVT::i32)),
        0);
    SDValue Zero = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(0, DL, MVT::i32)),
        0);
    SDNode *Sel = CurDAG->getMachineNode(GPUMin::SELP, DL, MVT::i32,
                                         N->getOperand(0), One, Zero);
    ReplaceNode(N, Sel);
    return;
  }

  if (N->getOpcode() == ISD::SIGN_EXTEND &&
      N->getOperand(0).getValueType() == MVT::i1) {
    SDLoc DL(N);
    SDValue Zero = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(0, DL, MVT::i32)),
        0);
    SDValue MinusOne = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(0xffffffffu, DL, MVT::i32)),
        0);
    SDNode *Sel = CurDAG->getMachineNode(GPUMin::SELP, DL, MVT::i32,
                                         N->getOperand(0), MinusOne, Zero);
    ReplaceNode(N, Sel);
    return;
  }

  SelectCode(N);
}

GPUMinDAGToDAGISelPass::GPUMinDAGToDAGISelPass(TargetMachine &TM)
    : SelectionDAGISelPass(
          std::make_unique<GPUMinDAGToDAGISel>(TM, TM.getOptLevel())) {}
