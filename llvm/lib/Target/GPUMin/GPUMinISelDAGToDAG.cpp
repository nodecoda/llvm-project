// Chapter 00 has no patterns, so this selector rejects every DAG node.  It
// exists to prove the target is wired into SelectionDAG: chapter 03 adds the
// first pattern (ret) and chapter 04 the ALU patterns.
//
// The manual Select hook is where later chapters add nodes that patterns
// cannot express: large constants, branches, frame indices and globals.
//
//===----------------------------------------------------------------------===//

#include "GPUMinISelDAGToDAG.h"
#include "GPUMinSubtarget.h"
#include "GPUMinTargetMachine.h"
#include "llvm/CodeGen/SelectionDAGISel.h"
#include "llvm/CodeGen/SelectionDAGNodes.h"
#include "llvm/Support/Debug.h"
#include "llvm/Support/MathExtras.h"

using namespace llvm;

#define DEBUG_TYPE "gpumin-isel"

namespace {

class GPUMinDAGToDAGISel : public SelectionDAGISel {
  const GPUMinSubtarget *Subtarget = nullptr;

public:
  GPUMinDAGToDAGISel(TargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISel(TM, OptLevel) {}

  void Select(SDNode *N) override;

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<GPUMinSubtarget>();
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

// Include the pieces autogenerated from the target description.
#include "GPUMinGenDAGISel.inc"
};

} // end anonymous namespace

void GPUMinDAGToDAGISel::Select(SDNode *N) {
  // Constants are the one node chapter 03 cannot express as a pattern:
  // `movi` only carries 16 bits, and a pattern would happily match a 32-bit
  // constant and truncate it.  Doing the range check here keeps the failure
  // explicit.  Chapter 04 adds the two-instruction sequence for wide values.
  if (N->getOpcode() == ISD::Constant) {
    int64_t V = cast<ConstantSDNode>(N)->getSExtValue();
    if (isInt<16>(V)) {
      SDLoc DL(N);
      SDValue Imm = CurDAG->getTargetConstant(V, DL, MVT::i32);
      SDNode *Mov = CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32, Imm);
      ReplaceNode(N, Mov);
      return;
    }
    LLVM_DEBUG(dbgs() << "GPUMin: constant " << V
                      << " needs more than 16 bits (chapter 04)\n");
  }

  // i1 -> i32.  A predicate register holds one bit, not a 0/1 value, so the
  // extension is a SELP against constants: 0/1 for zext, 0/-1 for sext.
  if (N->getOpcode() == ISD::ZERO_EXTEND &&
      N->getOperand(0).getValueType() == MVT::i1) {
    SDLoc DL(N);
    SDValue One = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(1, DL, MVT::i32)),
        0);
    SDValue Zero = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(0, DL, MVT::i32)),
        0);
    SDNode *Sel = CurDAG->getMachineNode(GPUMin::SELP, DL, MVT::i32,
                                         N->getOperand(0), One, Zero);
    ReplaceNode(N, Sel);
    return;
  }

  if (N->getOpcode() == ISD::SIGN_EXTEND &&
      N->getOperand(0).getValueType() == MVT::i1) {
    SDLoc DL(N);
    SDValue Zero = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(0, DL, MVT::i32)),
        0);
    SDValue MinusOne = SDValue(
        CurDAG->getMachineNode(GPUMin::MOVI, DL, MVT::i32,
                               CurDAG->getTargetConstant(-1, DL, MVT::i32)),
        0);
    SDNode *Sel = CurDAG->getMachineNode(GPUMin::SELP, DL, MVT::i32,
                                         N->getOperand(0), MinusOne, Zero);
    ReplaceNode(N, Sel);
    return;
  }

  SelectCode(N);
}

GPUMinDAGToDAGISelPass::GPUMinDAGToDAGISelPass(TargetMachine &TM)
    : SelectionDAGISelPass(
          std::make_unique<GPUMinDAGToDAGISel>(TM, TM.getOptLevel())) {}
