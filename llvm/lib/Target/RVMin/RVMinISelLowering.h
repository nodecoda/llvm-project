#ifndef LLVM_LIB_TARGET_RVMIN_RVMINISELLOWERING_H
#define LLVM_LIB_TARGET_RVMIN_RVMINISELLOWERING_H

#include "RVMinSelectionDAGInfo.h"
#include "llvm/CodeGen/TargetLowering.h"

namespace llvm {

class RVMinSubtarget;

// Chapter 40: the calling-convention half of the ABI.  The ISA decides which
// instructions exist; the ABI decides where values cross a function boundary.
//   ILP32   no F/D: f32 and f64 are softened into integer registers
//   ILP32F  F: f32 in fa0-fa7, f64 softened (D is not part of this ABI)
//   ILP32D  D: f32 and f64 in fa0-fa7 (chapter 41)
enum class RVMinABI { ILP32, ILP32F, ILP32D };

// RVMinISD::RET_FLAG and friends are generated by TableGen
// (-gen-sd-node-info) from the SDNode definitions in RVMinInstrInfo.td and
// included through RVMinSelectionDAGInfo.h.
class RVMinTargetLowering : public TargetLowering {
public:
  RVMinTargetLowering(const TargetMachine &TM, const RVMinSubtarget &STI);

  const char *getTargetNodeName(unsigned Opcode) const override;

  EVT getSetCCResultType(const DataLayout &DL, LLVMContext &Context,
                         EVT VT) const override;

  /// Chapter 40: any f32 bit pattern can be materialized with LUI+ADDI plus
  /// `fmv.w.x`, so an f32 constant never needs a constant pool entry.  The
  /// legalizer turns it into an opaque i32 constant plus a bitcast, which the
  /// selector matches as FMV_W_X.  This is what keeps the F chapter free of
  /// .rodata machinery.
  FPImmAction getFPImmAction(const APFloat &Imm, EVT VT,
                             bool ForCodeSize = false) const override;

  SDValue LowerOperation(SDValue Op, SelectionDAG &DAG) const override;

  /// Chapter 17: tell the IR-level tail call passes that RVMin can emit a
  /// real jump, so `return f(x);` keeps its `tail` marker.
  bool mayBeEmittedAsTailCall(const CallInst *CI) const override;

  /// Chapter 19: constant multiplies.  `x*3` becomes `x + (x<<1)` instead of
  /// a materialized constant plus `mul` (or `__mulsi3` without M).
  SDValue PerformDAGCombine(SDNode *N, DAGCombinerInfo &DCI) const override;

  /// Chapter 19: under `minsize`, a hardware div/rem is smaller than the
  /// magic-number sequence and should win the cost model.
  bool isIntDivCheap(EVT VT, AttributeList Attr) const override;

  /// Chapter 22: atomics.  Atomic loads and stores become `fence` plus an
  /// ordinary load/store; only read-modify-write operations keep an atomic
  /// node, and those are selected as AMO instructions.
  bool shouldInsertFencesForAtomic(const Instruction *I) const override {
    return true;
  }

  /// Chapter 22: operations with a native AMO stay in the DAG (see the
  /// patterns in RVMinInstrInfo.td); the rest become a cmpxchg loop.
  TargetLowering::AtomicExpansionKind
  shouldExpandAtomicRMWInIR(const AtomicRMWInst *RMW) const override;

  /// Chapter 22: a 32-bit cmpxchg becomes a `lr.w`/`sc.w` retry loop.
  /// Narrower cmpxchg values first widen to a word (see
  /// setMinCmpXchgSizeInBits(32)) and then use the same loop.
  TargetLowering::AtomicExpansionKind
  shouldExpandAtomicCmpXchgInIR(const AtomicCmpXchgInst *CI) const override {
    return CI->getCompareOperand()->getType()->isIntegerTy(32)
               ? AtomicExpansionKind::LLSC
               : AtomicExpansionKind::None;
  }

  /// Chapter 22: `lr.w` / `sc.w` for the LL/SC loop.  There is no target
  /// intrinsic yet, so the cleanest way to get exactly these two instructions
  /// into the loop is a single-instruction inline asm.
  Value *emitLoadLinked(IRBuilderBase &Builder, Type *ValueType, Value *Addr,
                        AtomicOrdering Ord) const override;
  Value *emitStoreConditional(IRBuilderBase &Builder, Value *Val, Value *Addr,
                              AtomicOrdering Ord) const override;

  /// Chapter 22: inline asm constraint support, needed by the two hooks above.
  std::pair<unsigned, const TargetRegisterClass *>
  getRegForInlineAsmConstraint(const TargetRegisterInfo *TRI,
                               StringRef Constraint, MVT VT) const override;

  SDValue LowerFormalArguments(SDValue Chain, CallingConv::ID CallConv,
                               bool IsVarArg,
                               const SmallVectorImpl<ISD::InputArg> &Ins,
                               const SDLoc &DL, SelectionDAG &DAG,
                               SmallVectorImpl<SDValue> &InVals) const override;

  SDValue LowerCall(CallLoweringInfo &CLI,
                    SmallVectorImpl<SDValue> &InVals) const override;

  bool CanLowerReturn(CallingConv::ID CallConv, MachineFunction &MF,
                      bool IsVarArg,
                      const SmallVectorImpl<ISD::OutputArg> &Outs,
                      LLVMContext &Context, const Type *RetTy) const override;

  SDValue LowerReturn(SDValue Chain, CallingConv::ID CallConv, bool IsVarArg,
                      const SmallVectorImpl<ISD::OutputArg> &Outs,
                      const SmallVectorImpl<SDValue> &OutVals, const SDLoc &DL,
                      SelectionDAG &DAG) const override;

private:
  SDValue lowerSELECT(SDValue Op, SelectionDAG &DAG) const;

  /// Chapter 48: vector constants and element extraction.  A splat in the
  /// 5-bit immediate range becomes VMV_V_I; everything else goes through a
  /// private 16-byte stack slot and VLE32_V (or a scalar LW for extract).
  SDValue lowerBUILD_VECTOR(SDValue Op, SelectionDAG &DAG) const;
  SDValue lowerSPLAT_VECTOR(SDValue Op, SelectionDAG &DAG) const;
  SDValue lowerEXTRACT_VECTOR_ELT(SDValue Op, SelectionDAG &DAG) const;
  SDValue lowerVectorThroughStack(ArrayRef<SDValue> Elems, const SDLoc &DL,
                                  SelectionDAG &DAG) const;

  /// Chapter 41: f64 constants have no `fmv.d.x` on RV32, and i64 is not a
  /// legal type here.  Materialize the bit pattern through a private 8-byte
  /// stack slot: two i32 stores followed by one `fld`.
  SDValue lowerConstantFP(SDValue Op, SelectionDAG &DAG) const;

  /// Resolve the ABI for a function: -target-abi / the "target-abi" module
  /// flag win, otherwise it is derived from the enabled extensions.
  RVMinABI getABI(const MachineFunction &MF) const;

  /// Reject ABI/ISA combinations this course does not implement, instead of
  /// silently generating calls that use the wrong set of registers.
  void checkABICompatibility(const MachineFunction &MF) const;

  SDValue lowerSELECT_CC(SDValue Op, SelectionDAG &DAG) const;
  SDValue lowerBRCOND(SDValue Op, SelectionDAG &DAG) const;
  SDValue lowerBR_CC(SDValue Op, SelectionDAG &DAG) const;
  SDValue lowerBR_JT(SDValue Op, SelectionDAG &DAG) const;
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_RVMIN_RVMINISELLOWERING_H
