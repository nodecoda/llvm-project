#ifndef LLVM_LIB_TARGET_RVMIN_MCTARGETDESC_RVMININSTPRINTER_H
#define LLVM_LIB_TARGET_RVMIN_MCTARGETDESC_RVMININSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class RVMinInstPrinter : public MCInstPrinter {
public:
  RVMinInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                   const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;
  void printRegName(raw_ostream &O, MCRegister Reg) override;

  void printOperand(const MCInst *MI, unsigned OpNo,
                    const MCSubtargetInfo &STI, raw_ostream &O);
  /// LUI/AUIPC's imm[31:12]: always print the unsigned 20-bit field value.
  void printUImm20Operand(const MCInst *MI, unsigned OpNo,
                          const MCSubtargetInfo &STI, raw_ostream &O);

  /// CSR operands print as `mstatus`/`fflags`/... when the encoding has a
  /// name in the chapter 46 table, and as a plain number otherwise.
  void printCSRSystemRegister(const MCInst *MI, unsigned OpNo,
                              const MCSubtargetInfo &STI, raw_ostream &O);

  /// Chapter 47: vtype operands print back as `e32, m1, ta, ma` when the
  /// encoded bits are a supported SEW/LMUL/policy combination, and as the
  /// raw integer otherwise.
  void printVTypeI(const MCInst *MI, unsigned OpNo,
                   const MCSubtargetInfo &STI, raw_ostream &O);

  // Autogenerated by tablegen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address,
                        const MCSubtargetInfo &STI, raw_ostream &O);
  bool printAliasInstr(const MCInst *MI, uint64_t Address,
                        const MCSubtargetInfo &STI, raw_ostream &O);
  void printCustomAliasOperand(const MCInst *MI, uint64_t Address,
                               unsigned OpIdx, unsigned PrintMethodIdx,
                               const MCSubtargetInfo &STI, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg, unsigned AltIdx);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_RVMIN_MCTARGETDESC_RVMININSTPRINTER_H
