// Chapter 3 uses the TableGen-generated pattern matcher for everything it can
// (constants, add, ret).  The manual Select hook is where later chapters add
// nodes that patterns cannot express: large constants (chapter 4), branches
// (chapter 5), frame indices (chapter 6), globals (chapter 7).
//
//===----------------------------------------------------------------------===//

#include "RVMin.h"
#include "RVMinISelDAGToDAG.h"
#include "RVMinSubtarget.h"
#include "RVMinTargetMachine.h"
#include "llvm/CodeGen/SelectionDAGISel.h"
#include "llvm/CodeGen/SelectionDAGNodes.h"
#include "llvm/Support/Debug.h"

using namespace llvm;

#define DEBUG_TYPE "rvmin-isel"

namespace {

class RVMinDAGToDAGISel : public SelectionDAGISel {
  const RVMinSubtarget *Subtarget = nullptr;

public:
  RVMinDAGToDAGISel(TargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISel(TM, OptLevel) {}

  void Select(SDNode *N) override;

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<RVMinSubtarget>();
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

// Include the pieces autogenerated from the target description.
#include "RVMinGenDAGISel.inc"
};

} // end anonymous namespace

void RVMinDAGToDAGISel::Select(SDNode *N) {
  if (N->isMachineOpcode()) {
    N->setNodeId(-1);
    return;
  }

  switch (N->getOpcode()) {
  default:
    break;
  // Chapter 4 will select large constants with LUI+ADDI here.
  }

  SelectCode(N);
}

RVMinDAGToDAGISelPass::RVMinDAGToDAGISelPass(TargetMachine &TM)
    : SelectionDAGISelPass(
          std::make_unique<RVMinDAGToDAGISel>(TM, TM.getOptLevel())) {}
