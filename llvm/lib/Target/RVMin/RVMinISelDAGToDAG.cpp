namespace {

/// Recognize a stack address: either a bare `frameindex` or
/// `frameindex + constant`.  GEPs with constant indices are folded this way,
/// so `alloca [4 x i32]` + index 2 reaches us as FI + 8.
bool matchFrameAddr(SDValue Addr, SDValue &FI, int64_t &Offset) {
  if (isa<FrameIndexSDNode>(Addr)) {
    FI = Addr;
    Offset = 0;
    return true;
  }
  if (Addr.getOpcode() == ISD::ADD &&
      isa<ConstantSDNode>(Addr.getOperand(1)) &&
      isa<FrameIndexSDNode>(Addr.getOperand(0))) {
    FI = Addr.getOperand(0);
    Offset = cast<ConstantSDNode>(Addr.getOperand(1))->getSExtValue();
    return true;
  }
  return false;
}

} // end anonymous namespace

void RVMinDAGToDAGISel::Select(SDNode *N) {
  if (N->isMachineOpcode()) {
    N->setNodeId(-1);
    return;
  }

  SDLoc DL(N);

  // Materialize integer constants.  RV32I has no "load immediate", so this is
  // ADDI for the 12-bit range and LUI+ADDI for everything else:
  //
  //   imm = (hi20 << 12) + lo12,  lo12 in [-2048, 2047]
  //
  // LUI writes hi20 into bits 31:12 and sign-extends the result, which is why
  // the pairing covers the whole 32-bit range (including INT32_MIN).
  if (N->getOpcode() == ISD::Constant) {
    int64_t Imm = cast<ConstantSDNode>(N)->getSExtValue();
    SDValue Zero = CurDAG->getRegister(RVMin::X0, MVT::i32);
    auto targetImm = [&](int64_t V) {
      return CurDAG->getTargetConstant(
          APInt(32, static_cast<uint64_t>(V), /*isSigned=*/true), DL, MVT::i32);
    };

    // zero is the x0 register, not an ADDI.
    if (Imm == 0) {
      ReplaceNode(N, Zero.getNode());
      return;
    }

    if (isInt<12>(Imm)) {
      SDValue ImmV = targetImm(Imm);
      ReplaceNode(N, CurDAG->getMachineNode(RVMin::ADDI, DL, MVT::i32, Zero,
                                            ImmV));
      return;
    }

    int64_t Hi = (Imm + 0x800) >> 12;
    int64_t Lo = Imm - (Hi << 12);
    assert(isInt<12>(Lo) && "LUI+ADDI split is always encodable");
    SDValue HiV = targetImm(Hi);
    SDValue LoV = targetImm(Lo);
    SDValue Lui =
        SDValue(CurDAG->getMachineNode(RVMin::LUI, DL, MVT::i32, HiV), 0);
    ReplaceNode(
        N, CurDAG->getMachineNode(RVMin::ADDI, DL, MVT::i32, Lui, LoV));
    return;
  }

  // A frame index used as a value is the address of a stack object.  Select it
  // as `addi rd, sp, offset`; eliminateFrameIndex fills in the real offset and
  // base after register allocation.
  if (N->getOpcode() == ISD::FrameIndex) {
    int FI = cast<FrameIndexSDNode>(N)->getIndex();
    SDValue TFI = CurDAG->getTargetFrameIndex(FI, MVT::i32);
    SDValue Zero = CurDAG->getTargetConstant(0, DL, MVT::i32);
    ReplaceNode(N, CurDAG->getMachineNode(RVMin::ADDI, DL, MVT::i32, TFI,
                                          Zero));
    return;
  }

  // Stack accesses.  Fold the frame index (and any constant offset folded into
  // the address by DAGCombine) into the load/store immediate, so the result is
  // a single `lw/sw rd, off(sp)`.  Everything else falls through to the
  // TableGen patterns at the end of Select.
  if (N->getOpcode() == ISD::LOAD) {
    LoadSDNode *LD = cast<LoadSDNode>(N);
    SDValue FI;
    int64_t Off;
    if (LD->getMemoryVT() == MVT::i32 &&
        matchFrameAddr(LD->getBasePtr(), FI, Off)) {
      SDValue TFI =
          CurDAG->getTargetFrameIndex(cast<FrameIndexSDNode>(FI)->getIndex(),
                                      MVT::i32);
      SDValue Imm = CurDAG->getTargetConstant(Off, DL, MVT::i32);
      // Machine nodes put the chain after the explicit operands.
      SDValue Ops[] = {TFI, Imm, LD->getChain()};
      MachineSDNode *MN = CurDAG->getMachineNode(RVMin::LW, DL, MVT::i32,
                                                 MVT::Other, Ops);
      CurDAG->setNodeMemRefs(MN, {LD->getMemOperand()});
      ReplaceNode(N, MN);
      return;
    }
  }

  if (N->getOpcode() == ISD::STORE) {
    StoreSDNode *ST = cast<StoreSDNode>(N);
    SDValue FI;
    int64_t Off;
    if (ST->getMemoryVT() == MVT::i32 &&
        matchFrameAddr(ST->getBasePtr(), FI, Off)) {
      SDValue TFI =
          CurDAG->getTargetFrameIndex(cast<FrameIndexSDNode>(FI)->getIndex(),
                                      MVT::i32);
      SDValue Imm = CurDAG->getTargetConstant(Off, DL, MVT::i32);
      SDValue Ops[] = {ST->getValue(), TFI, Imm, ST->getChain()};
      MachineSDNode *MN = CurDAG->getMachineNode(RVMin::SW, DL, MVT::Other,
                                                 Ops);
      CurDAG->setNodeMemRefs(MN, {ST->getMemOperand()});
      ReplaceNode(N, MN);
      return;
    }
  }

  // Global addresses: RV32I has no absolute addressing mode, so materialize
  // the address with the canonical %hi/%lo pair:
  //
  //   lui  rd, %hi(sym)
  //   addi rd, rd, %lo(sym)
  //
  // The two halves carry different target flags; the asm printer turns them
  // into relocation specifiers and the ELF writer into R_RISCV_HI20/LO12.
  if (N->getOpcode() == ISD::GlobalAddress) {
    auto *GA = cast<GlobalAddressSDNode>(N);
    const GlobalValue *GV = GA->getGlobal();
    int64_t Off = GA->getOffset();
    SDValue Hi = CurDAG->getTargetGlobalAddress(GV, DL, MVT::i32, Off,
                                                RVMinII::MO_HI20);
    SDValue Lo = CurDAG->getTargetGlobalAddress(GV, DL, MVT::i32, Off,
                                                RVMinII::MO_LO12_I);
    SDValue Lui =
        SDValue(CurDAG->getMachineNode(RVMin::LUI, DL, MVT::i32, Hi), 0);
    ReplaceNode(N,
                CurDAG->getMachineNode(RVMin::ADDI, DL, MVT::i32, Lui, Lo));
    return;
  }

  SelectCode(N);
}

RVMinDAGToDAGISelPass::RVMinDAGToDAGISelPass(TargetMachine &TM)
    : SelectionDAGISelPass(
          std::make_unique<RVMinDAGToDAGISel>(TM, TM.getOptLevel())) {}
